"""Human-readable inventory of every tool Jarvis can offer, by surface and effect."""

from __future__ import annotations

from jarvis.agent.permissions import (
    CONFIRM_TOOLS,
    CONTROL_TOOLS,
    EXTERNAL_TOOLS,
    LOCAL_TOOLS,
    READ_TOOLS,
)
from jarvis.agent.routing import SYSTEM_CAPABILITIES
from jarvis.agent.tool_registry import ToolRegistry
from jarvis.desktop.cua import CuaDesktop, register_desktop_tools
from jarvis.tools.browser_tools import register_browser_tools
from jarvis.tools.system_tools import register_system_tools
from jarvis.utils.config import JarvisConfig

_EFFECTS = (
    ("read", READ_TOOLS),
    ("local edit", LOCAL_TOOLS),
    ("control", CONTROL_TOOLS),
    ("outward", EXTERNAL_TOOLS),
)


def _effect(name: str) -> str:
    return next((label for label, names in _EFFECTS if name in names), "unclassified")


def _group(name: str) -> str:
    return next((group for group, names in SYSTEM_CAPABILITIES.items() if name in names), "-")


def _summary(description: str) -> str:
    first = " ".join(description.split()).split(". ")[0].rstrip(".")
    return first.replace("|", "/")


def _section(title: str, note: str, registry: ToolRegistry, *, grouped: bool) -> list[str]:
    header = "| Tool | Capability | Effect | Confirms | What it does |" if grouped else \
        "| Tool | Effect | Confirms | What it does |"
    rule = "|---|---|---|---|---|" if grouped else "|---|---|---|---|"
    lines = [f"## {title} ({len(registry)})", "", note, "", header, rule]
    for name in sorted(registry.list_tools()):
        tool = registry.get(name)
        confirms = "yes" if name in CONFIRM_TOOLS or tool.requires_confirmation else "no"
        cells = [f"`{name}`", *([_group(name)] if grouped else []), _effect(name), confirms,
                 _summary(tool.description)]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def render_tool_table(config: JarvisConfig | None = None) -> str:
    """Markdown listing of all registered tools. Needs no running services."""
    config = config or JarvisConfig()
    system, browser, desktop = ToolRegistry(), ToolRegistry(), ToolRegistry()
    register_system_tools(system, config.security, llm_client=object())  # object(): enables vision tools
    register_browser_tools(browser)
    register_desktop_tools(desktop, CuaDesktop(config.desktop))

    lines = [
        "# Tool inventory",
        "",
        "Generated by `jarvis --list-tools`; a test keeps this file current.",
        "",
        "A request is routed to exactly one surface and the model is offered only that",
        "surface's tools (see `jarvis/agent/routing.py`). \"Confirms\" means the tool asks for",
        "an exact yes when `security.confirm_dangerous_ops` is on. Every call is also",
        "checked by the permission gateway ([security](security.md)).",
        "",
    ]
    lines += _section("System tools", "Offered per request by capability group "
                      "(files, shell, clock, clipboard, ...).", system, grouped=True)
    lines += _section("Browser tools", "Offered for web tasks (Playwright, Chromium).",
                      browser, grouped=False)
    lines += _section("Desktop tools", "Offered for window and app tasks when "
                      "`desktop.backend: cua`.", desktop, grouped=False)
    return "\n".join(lines).rstrip("\n") + "\n"
