"""Test faster-whisper STT engine."""
import asyncio
import os
import sys

sys.path.insert(0, ".")

from jarvis.utils.config import load_config


async def test_stt():
    config = load_config()

    print("1. Initializing faster-whisper STT...")
    try:
        from faster_whisper import WhisperModel
    except ImportError:
        print("faster-whisper not installed.")
        return

    model_size = config.voice.stt.model      # default: small
    compute_type = config.voice.stt.compute_type  # default: int8 (CPU)

    print(f"   Model: {model_size}, Compute: {compute_type}")

    try:
        # Download and load model (takes time on first run)
        model = WhisperModel(model_size, device="cpu", compute_type=compute_type)
        print("Model loaded.")
    except Exception as e:
        print(f"Failed to load model: {e}")
        return

    # Use the audio file generated by the TTS test
    test_audio = ".jarvis_test/tts_test_0.wav"
    if not os.path.exists(test_audio):
        print(f"Test audio file not found: {test_audio}")
        print("   Please run test_tts.py first.")
        return

    print(f"\n2. Transcribing audio file ({test_audio})...")

    try:
        segments, info = model.transcribe(
            test_audio,
            beam_size=config.voice.stt.beam_size,
            language=config.voice.stt.language
        )

        print(f"Detected language '{info.language}' with probability {info.language_probability:.2f}")

        print("\n--- Transcription ---")
        full_text = ""
        for segment in segments:
            text = segment.text.strip()
            print(f"[{segment.start:.2f}s -> {segment.end:.2f}s] {text}")
            full_text += text + " "

        print("\n--- Summary ---")
        print(f"Final text: {full_text.strip()}")

    except Exception as e:
        print(f"Transcription failed: {e}")
        return

    print("\nSTT test complete!")


if __name__ == "__main__":
    asyncio.run(test_stt())
